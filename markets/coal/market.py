"""煤炭 · 煤焦钢产业链: coking coal → coke → rebar, with iron ore as the other steel input.

Thermal coal (ZC) stopped trading in 2022, so the tradable chain is DCE coking coal / coke and SHFE rebar.
"""
from nevacore.spec import Instrument, Node, Relation, Series, carry, carry_series, define_market, momentum

INSTS = [("JM", "焦煤", "Coking coal"), ("J", "焦炭", "Coke"), ("RB", "螺纹", "Rebar"), ("I", "铁矿", "Iron ore")]
CN = dict(exchange="DCE", currency="CNY", unit="元/吨", fee_rate=0.0001, quote="nf_")

MARKET = define_market(
    key="coal",
    name="煤炭",
    name_en="Coal",
    tagline="焦煤、焦炭、螺纹钢、铁矿石：煤焦钢产业链的价格、利润和基差",
    tagline_en="Coking coal, coke, rebar and iron ore: prices, margins and basis along the coal–coke–steel chain",
    currency="CNY",
    start="2019-01-02",
    main="JM",
    instruments=[
        Instrument("JM", "焦煤", "Coking coal", multiplier=60, margin=0.15, tick=0.5,
                   source={"kind": "cn_future", "symbol": "JM", "months": [1, 5, 9]}, **CN),
        Instrument("J", "焦炭", "Coke", multiplier=100, margin=0.15, tick=0.5,
                   source={"kind": "cn_future", "symbol": "J", "months": [1, 5, 9]}, **CN),
        Instrument("RB", "螺纹钢", "Rebar", multiplier=10, margin=0.10, tick=1,
                   source={"kind": "cn_future", "symbol": "RB", "months": [1, 5, 10]}, **{**CN, "exchange": "SHFE"}),
        Instrument("I", "铁矿石", "Iron ore", multiplier=100, margin=0.13, tick=0.5,
                   source={"kind": "cn_future", "symbol": "I", "months": [1, 5, 9]}, **CN),
    ],
    series=[
        Series("JM.basis", "焦煤基差率", "Coking coal basis", "%", "基差", "Basis", source={"kind": "cn_basis", "var": "JM"},
               formula="(现货 − 主力合约) ÷ 现货"),
        Series("J.basis", "焦炭基差率", "Coke basis", "%", "基差", "Basis", source={"kind": "cn_basis", "var": "J"},
               formula="(现货 − 主力合约) ÷ 现货"),
        Series("RB.basis", "螺纹基差率", "Rebar basis", "%", "基差", "Basis", source={"kind": "cn_basis", "var": "RB"},
               formula="(现货 − 主力合约) ÷ 现货"),
        Series("JM.spot", "焦煤现货", "Coking coal spot", "元/吨", "现货", "Spot", source={"kind": "cn_basis", "var": "JM"}),
        Series("J.spot", "焦炭现货", "Coke spot", "元/吨", "现货", "Spot", source={"kind": "cn_basis", "var": "J"}),
        *[carry_series(i, n, e) for i, n, e in INSTS],
        Series("coke_margin", "焦化盘面利润", "Coking margin", "元/吨", "利润", "Margin",
               derive=lambda f: f["J"] - 1.33 * f["JM"], formula="焦炭 − 1.33 × 焦煤（未扣加工费，只看相对变化）"),
        Series("steel_margin", "螺纹盘面利润", "Rebar mill margin", "元/吨", "利润", "Margin",
               derive=lambda f: f["RB"] - 1.6 * f["I"] - 0.5 * f["J"], formula="螺纹 − 1.6 × 铁矿 − 0.5 × 焦炭（未扣其他成本）"),
    ],
    relations=[
        Relation("jm_to_j", "JM", "J", "pct", window=5, lag=0, horizon=5, sign=1,
                 name="焦煤涨 → 焦炭跟涨", name_en="Coking coal up → coke follows",
                 why="约 1.33 吨焦煤炼 1 吨焦炭，焦煤是焦炭最大的成本，原料涨价会推着焦炭提涨。",
                 why_en="About 1.33 t of coking coal makes 1 t of coke; dearer coal pushes coke prices up."),
        Relation("rb_to_j", "RB", "J", "pct", window=5, lag=0, horizon=5, sign=1,
                 name="钢价涨 → 焦炭需求升", name_en="Steel up → coke demand up",
                 why="钢价走强时钢厂提高开工、补库焦炭，焦炭需求跟着上来。",
                 why_en="Stronger steel prices lift mill run rates and coke restocking."),
        Relation("steel_margin_to_j", "steel_margin", "J", "level", window=250, lag=0, horizon=10, sign=1,
                 name="钢厂利润高 → 焦炭能提涨", name_en="Fat mill margins → coke can rise",
                 why="钢厂有利润时愿意接受焦炭提涨；利润被压缩时会反过来压价焦炭。",
                 why_en="Profitable mills accept coke price hikes; squeezed mills push coke prices down."),
        Relation("steel_margin_to_i", "steel_margin", "I", "level", window=250, lag=0, horizon=10, sign=1,
                 name="钢厂利润高 → 铁矿需求强", name_en="Fat mill margins → ore demand",
                 why="利润好时高炉开工率高，铁矿石消耗和补库都会增加。",
                 why_en="High margins keep blast furnaces running and ore restocking strong."),
        Relation("coke_margin_to_jm", "coke_margin", "JM", "level", window=250, lag=0, horizon=10, sign=1,
                 name="焦化利润高 → 多采购焦煤", name_en="Coking margin up → more coal buying",
                 why="焦化厂有利润就多开工、多采购焦煤，焦煤需求上升。",
                 why_en="Profitable coking plants run harder and buy more coking coal."),
        Relation("coke_margin_to_j", "coke_margin", "J", "level", window=250, lag=0, horizon=10, sign=-1,
                 name="焦化利润过高 → 焦炭供给增、利润回落", name_en="High coking margin → more coke supply",
                 why="焦化利润过高会刺激焦炭增产，供给增加后焦炭价格回落、利润回归。",
                 why_en="Excess coking margins draw out more coke supply until the margin mean-reverts."),
        Relation("jm_basis", "JM.basis", "JM", "level", window=250, lag=0, horizon=10, sign=1,
                 name="焦煤现货升水大 → 期货向现货收敛", name_en="Coking coal basis wide → futures converge up",
                 why="期货临近交割要向现货收敛，现货相对期货越贵，期货补涨的动力越大。",
                 why_en="Futures converge to spot into delivery; a wide premium of spot pulls futures up."),
        Relation("j_basis", "J.basis", "J", "level", window=250, lag=0, horizon=10, sign=1,
                 name="焦炭现货升水大 → 期货向现货收敛", name_en="Coke basis wide → futures converge up",
                 why="同焦煤：基差越大，期货向现货收敛的动力越强。",
                 why_en="As with coal: the wider the basis, the stronger the pull on futures."),
        Relation("rb_basis", "RB.basis", "RB", "level", window=250, lag=0, horizon=10, sign=1,
                 name="螺纹现货升水大 → 期货向现货收敛", name_en="Rebar basis wide → futures converge up",
                 why="现货偏强说明终端需求好于盘面预期，期货往现货靠。",
                 why_en="A firm spot market signals real demand ahead of futures pricing."),
        Relation("i_to_rb", "I", "RB", "pct", window=5, lag=0, horizon=5, sign=1,
                 name="铁矿涨 → 螺纹成本推升", name_en="Iron ore up → rebar cost push",
                 why="约 1.6 吨铁矿炼 1 吨钢，铁矿是螺纹最大的原料成本。",
                 why_en="About 1.6 t of ore goes into 1 t of steel; ore is rebar's largest input cost."),
        *[momentum(i, n, e) for i, n, e in INSTS],
        *[carry(i, n, e) for i, n, e in INSTS],
    ],
    nodes=[
        Node("JM", 0.08, 0.28, "上游"), Node("I", 0.08, 0.78, "上游"),
        Node("JM.basis", 0.08, 0.04, "上游"),
        Node("coke_margin", 0.30, 0.52, "中游"),
        Node("J", 0.52, 0.28, "中游"), Node("J.basis", 0.52, 0.04, "中游"),
        Node("steel_margin", 0.72, 0.62, "下游"),
        Node("RB", 0.93, 0.28, "下游"), Node("RB.basis", 0.93, 0.04, "下游"),
    ],
)
